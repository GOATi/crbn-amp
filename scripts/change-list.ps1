<#
.SYNOPSIS
  Writes CRBN Rig's change list: every upstream file GOATi changed, removed or added since the fork, from git.
.DESCRIPTION
  The suite ships one generated change list per repo with every build (crbn-launcher docs/DECISIONS.md D-CRBN-007),
  regenerated by each build so it is never stale. Upstream here is MIT, which does not ask for it; CRBN Rig ships it
  anyway, as every CRBN app does. packaging/windows/package.ps1 and the web build call this; it can be run by hand.
  The list compares the fork's baseline (UPSTREAM.md: sdatkinson/NeuralAmpModelerPlugin at fee982a) with the commit
  being built (HEAD by default). The submodules (iPlug2, NeuralAmpModelerCore, AudioDSPTools, Eigen) are upstream's
  own repos at the commits UPSTREAM.md names; a moved pointer shows here as a changed path. A dirty working tree is
  named in the header, since the build may contain changes the commit does not.
.EXAMPLE
  pwsh scripts/change-list.ps1 -Out dist/hub/crbn-rig-0.8.0-windows-x64/MODIFIED-FILES.txt
#>
param(
  [string] $Out = '',
  [string] $Commit = 'HEAD',
  [string] $Baseline = 'fee982a86096ea17e7a6b004577207ab7c460e0c'
)
$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
function Invoke-Git([string[]] $GitArgs) {
  $out = & git.exe -C $Root @GitArgs
  if ($LASTEXITCODE -ne 0) { throw "git $($GitArgs -join ' ') failed with exit code $LASTEXITCODE" }
  $out
}
$base = Invoke-Git @('rev-parse', '--verify', "$Baseline^{commit}")
$head = Invoke-Git @('rev-parse', '--verify', "$Commit^{commit}")
$dirty = @(Invoke-Git @('status', '--porcelain', '--untracked-files=no', '--ignore-submodules=dirty')).Count -gt 0
# -M: a renamed file is listed once, with its old path. core.quotepath off keeps non-ASCII names readable.
$rows = Invoke-Git @('-c', 'core.quotepath=off', 'diff', '--name-status', '-M', $base, $head)
# The vendored libraries (vendor.json, D-RIG-001): their files arrived as upstream's own blobs, so they are listed as
# vendored at their upstream commits, not as GOATi's additions, and the submodule pointers they replaced are not
# "removed". A change to one of their files after vendoring is listed under its own heading.
$vendorFile = Join-Path $Root 'vendor.json'
$vendored = if (Test-Path $vendorFile) { (Get-Content $vendorFile -Raw | ConvertFrom-Json).libraries } else { @() }
$vendorPaths = @($vendored | ForEach-Object { $_.path })
$inVendored = { param($p) foreach ($v in $vendorPaths) { if ($p -eq $v -or $p -eq '.gitmodules' -or $p.StartsWith("$v/")) { return $true } } return $false }
$changed = @(); $removed = @(); $added = @()
foreach ($row in $rows) {
  $f = $row -split "`t"
  if ($vendorPaths.Count -and (& $inVendored $f[-1])) { continue }
  switch -Regex ($f[0]) {
    '^M' { $changed += $f[1] }
    '^R' { $changed += "$($f[2])  (was $($f[1]))" }
    '^T' { $changed += $f[1] }
    '^D' { $removed += $f[1] }
    '^[AC]' { $added += $f[-1] }
  }
}
# Changes to vendored files since the commit that vendored them (the first that added vendor.json).
$vendorChanged = @()
$vendorCommit = @(Invoke-Git @('log', '--diff-filter=A', '--format=%H', $head, '--', 'vendor.json')) | Select-Object -Last 1
if ($vendorCommit -and $vendorPaths.Count) {
  $vendorChanged = @(Invoke-Git (@('-c', 'core.quotepath=off', 'diff', '--name-status', '-M', $vendorCommit, $head, '--') + $vendorPaths) | ForEach-Object { ($_ -split "`t")[-1] })
}
$lines = @(
  'CRBN Rig: files changed from the original'
  ''
  'CRBN Rig is based on Neural Amp Modeler by Steven Atkinson (https://github.com/sdatkinson/NeuralAmpModelerPlugin),'
  'used under the MIT License (LICENSE.txt). GOATi Entertainment Pty Ltd changed the files listed below from the'
  "original. The original is sdatkinson/NeuralAmpModelerPlugin at commit $base; this build's source is GOATi's"
  "commit $head (https://github.com/GOATi/crbn-amp, private)."
)
if ($dirty) { $lines += 'The build was made from a working tree with uncommitted changes, so it may differ from that commit.' }
$lines += ''
$lines += "Changed ($($changed.Count)):"; $lines += ($changed | Sort-Object | ForEach-Object { "  $_" }); $lines += ''
$lines += "Removed ($($removed.Count)):"; $lines += ($removed | Sort-Object | ForEach-Object { "  $_" }); $lines += ''
$lines += "Added by GOATi ($($added.Count)):"; $lines += ($added | Sort-Object | ForEach-Object { "  $_" })
if ($vendored.Count) {
  $lines += ''
  $lines += "Libraries vendored from their upstreams ($($vendored.Count)), each trimmed to what builds, every kept file upstream's own when vendored:"
  foreach ($v in $vendored) { $lines += "  $($v.path)/  $($v.upstream) at $($v.commit), $($v.kept) of $($v.of) files (left out: $($v.leftOut))" }
  $lines += ''
  $lines += "Changed in the vendored libraries since they were vendored ($($vendorChanged.Count)):"; $lines += ($vendorChanged | Sort-Object | ForEach-Object { "  $_" })
}
$text = ($lines -join "`r`n") + "`r`n"
if ($Out) {
  $dir = Split-Path -Parent $Out
  if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
  [IO.File]::WriteAllText($Out, $text, (New-Object Text.UTF8Encoding($false)))
  Write-Host "change list: $($changed.Count) changed, $($removed.Count) removed, $($added.Count) added -> $Out"
} else { $text }
